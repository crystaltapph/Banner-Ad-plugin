/* Run against the disposable Compose site after tests/setup.php. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.BAP_TEST_URL || 'http://127.0.0.1:8080';
const fixture = JSON.parse(fs.readFileSync(process.env.BAP_FIXTURE || '/tmp/banner-fixture.json', 'utf8'));
const out = process.env.BAP_TEST_OUTPUT || '/tmp/banner-studio-results';
fs.mkdirSync(out, { recursive: true });
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; console.log(`PASS ${message}`); };
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const errors = [];
  try {
    const admin = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await admin.newPage();
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(`${base}/wp-login.php`);
    await page.locator('#user_login').fill('banner-tester');
    await page.locator('#user_pass').fill('local-ui-test-only');
    await Promise.all([page.waitForURL('**/wp-admin/**'), page.locator('#wp-submit').click()]);
    await page.goto(`${base}/wp-admin/admin.php?page=banner-studio`);
    check(await page.getByRole('heading', { name: /^Banner Studio 1\./ }).isVisible(), 'Dashboard loads without a plugin error');
    await page.screenshot({ path: `${out}/dashboard.png`, fullPage: true });
    // Remove banners from a previous UI test run through the actual secured delete form.
    await page.goto(`${base}/wp-admin/admin.php?page=bap-banners`);
    page.on('dialog', dialog => dialog.accept());
    while (await page.locator('[data-bap-row]').count()) {
      await Promise.all([page.waitForURL('**bap_notice=deleted'), page.locator('.bap-delete button').first().click()]);
      await page.reload();
    }
    const choose = async (index, name) => {
      await page.getByRole('button', { name: 'Choose image', exact: true }).nth(index).click();
      const library = page.getByRole('tab', { name: 'Media Library' });
      if (await library.isVisible()) await library.click();
      await page.locator(`.media-modal:visible .attachment[aria-label="${name}"]`).click();
      await page.getByRole('button', { name: 'Use this image', exact: true }).click();
    };
    await page.goto(`${base}/wp-admin/admin.php?page=bap-banners&edit=new`);
    await page.getByLabel('Banner name', { exact: true }).fill('Browser test in-content');
    await choose(0, 'Test desktop artwork');
    await choose(1, 'Test mobile artwork');
    await page.locator('#bap-alt').fill('Explore our collection');
    await page.locator('#bap-url').fill('https://example.test/collection');
    await page.getByLabel('Open link in a new tab').check();
    await page.getByLabel('Paragraph / heading number').fill('2');
    await page.getByRole('button', { name: 'Mobile', exact: true }).click();
    check((await page.locator('#bap-preview-image').getAttribute('src')).includes('banner-test-mobile'), 'Live mobile preview uses mobile artwork');
    await page.screenshot({ path: `${out}/editor.png`, fullPage: true });
    await Promise.all([page.waitForURL('**bap_notice=saved'), page.getByRole('button', { name: 'Save banner', exact: true }).first().click()]);
    check(await page.getByText('Browser test in-content', { exact: true }).isVisible(), 'Banner created through Media Library and saved');
    await page.locator('#bap-search').fill('no-match');
    check(await page.locator('#bap-no-results').isVisible(), 'Banner search empty state works');
    await page.locator('#bap-search').fill('');
    await page.getByRole('link', { name: 'Edit', exact: true }).first().click();
    check((await page.locator('#bap-url').inputValue()) === 'https://example.test/collection', 'Saved destination persists on edit');
    await page.goto(`${base}/wp-admin/admin.php?page=bap-banners&edit=new`);
    await page.getByLabel('Banner name', { exact: true }).fill('Browser test sticky');
    await choose(1, 'Test mobile artwork');
    await page.getByLabel('Placement', { exact: true }).selectOption('sticky');
    await page.getByLabel('Show on desktop (768px+)').uncheck();
    await page.getByRole('button', { name: 'Mobile', exact: true }).click();
    check(await page.locator('#bap-preview-device.is-sticky').count(), 'Sticky mobile creative preview is available');
    await Promise.all([page.waitForURL('**bap_notice=saved'), page.getByRole('button', { name: 'Save banner', exact: true }).first().click()]);
    await page.goto(`${base}/wp-admin/admin.php?page=bap-banners`);
    await page.screenshot({ path: `${out}/banners.png`, fullPage: true });
    await page.goto(`${base}/wp-admin/admin.php?page=bap-settings`);
    await page.getByLabel('Remember dismissal (hours)').fill('12');
    await Promise.all([page.waitForURL('**bap_notice=settings'), page.getByRole('button', { name: 'Save settings' }).click()]);
    check(await page.getByLabel('Remember dismissal (hours)').inputValue() === '12', 'Global settings save and persist');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: `${out}/admin-mobile.png`, fullPage: true });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Admin settings fit a mobile viewport');
    const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const article = await desktop.newPage();
    article.on('pageerror', e => errors.push(e.message));
    await article.goto(`${base}/?p=${fixture.post}`);
    const inline = article.locator('.bap-banner:not(.bap-sticky)').first();
    await inline.scrollIntoViewIfNeeded();
    await article.waitForFunction(() => document.querySelector('.bap-banner img')?.complete);
    check(await inline.locator('img').evaluate(img => img.currentSrc.includes('banner-test-desktop')), 'Desktop article selects desktop image');
    check(await inline.locator('img').evaluate(img => img.naturalWidth > 0), 'Desktop banner image actually loads');
    check(await inline.locator('a').getAttribute('rel') === 'sponsored noopener', 'Frontend paid link attributes are correct');
    check(await article.locator('.bap-sticky').isHidden(), 'Mobile sticky banner stays hidden on desktop');
    check(await article.locator('.bap-banner:not(.bap-sticky)').evaluate(el => el.previousElementSibling.textContent.startsWith('Paragraph 2.')), 'Actual article banner follows paragraph two');
    await article.screenshot({ path: `${out}/desktop-article.png` });
    const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 2, hasTouch: true });
    const phone = await mobile.newPage();
    phone.on('pageerror', e => errors.push(e.message));
    await phone.goto(`${base}/?p=${fixture.post}`);
    check(await phone.locator('.bap-sticky').isHidden(), 'Sticky starts hidden before scrolling');
    await phone.locator('.bap-banner:not(.bap-sticky)').first().scrollIntoViewIfNeeded();
    await phone.waitForFunction(() => !document.querySelector('.bap-sticky').hidden);
    await phone.waitForFunction(() => document.querySelector('.bap-banner:not(.bap-sticky) img').complete);
    check(await phone.locator('.bap-banner:not(.bap-sticky) img').first().evaluate(img => img.currentSrc.includes('banner-test-mobile') && img.naturalWidth === 320), 'Mobile viewport loads mobile artwork');
    check(await phone.locator('.bap-sticky img').evaluate(img => img.getBoundingClientRect().height <= 100), 'Sticky artwork respects height limit');
    check(await phone.locator('#bap-sticky-space').evaluate(el => el.getBoundingClientRect().height > 0), 'Sticky reserves page-bottom space');
    check(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Frontend has no horizontal overflow on mobile');
    await phone.screenshot({ path: `${out}/mobile-article.png` });
    await phone.evaluate(() => { document.documentElement.dataset.bapOverlay = 'true'; });
    await phone.waitForFunction(() => document.querySelector('.bap-sticky').hidden);
    check(await phone.locator('.bap-sticky').isHidden(), 'Overlay integration hides sticky banner');
    await phone.evaluate(() => { delete document.documentElement.dataset.bapOverlay; });
    await phone.waitForFunction(() => !document.querySelector('.bap-sticky').hidden);
    await phone.getByRole('button', { name: 'Dismiss advertisement' }).click();
    check(await phone.locator('.bap-sticky').isHidden(), 'Close button dismisses sticky banner');
    await phone.reload();
    await phone.evaluate(() => window.scrollTo(0, 500));
    await phone.waitForTimeout(150);
    check(await phone.locator('.bap-sticky').isHidden(), 'Dismissal survives page reload');
    check(await phone.locator('#bap-sticky-space').evaluate(el => el.getBoundingClientRect().height === 0), 'Dismissal removes reserved space');
    await phone.goto(`${base}/?page_id=${fixture.page}`);
    check(await phone.locator('.bap-banner').count() === 0, 'Post-only banners do not appear on pages');
    check(errors.length === 0, `No browser JavaScript errors: ${errors.join('; ')}`);
    console.log(`\n${checks} browser checks passed. Screenshots: ${out}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
